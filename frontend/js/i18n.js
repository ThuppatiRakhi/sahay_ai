  var currentLanguage = DEFAULT_LANG;

  function getLanguage() {
    return currentLanguage;
  }

  function getVoiceLocale(lang) {
    var target = (lang || currentLanguage || DEFAULT_LANG).toLowerCase();
    if (target.indexOf('te') === 0) return 'te-IN';
    if (target.indexOf('hi') === 0) return 'hi-IN';
    return 'en-IN';
  }

  function t(key, params, defaultText) {
    if (!key || typeof key !== 'string') return defaultText || '';
    var parts = key.split('.');
    var val = LOCALES[currentLanguage];
    for (var i = 0; i < parts.length; i++) {
      val = val ? val[parts[i]] : undefined;
    }
    if (val === undefined && currentLanguage !== DEFAULT_LANG) {
      val = LOCALES[DEFAULT_LANG];
      for (var j = 0; j < parts.length; j++) {
        val = val ? val[parts[j]] : undefined;
      }
    }
    if (val === undefined) {
      val = defaultText !== undefined ? defaultText : key;
    }
    if (typeof val === 'string' && params && typeof params === 'object') {
      val = val.replace(/\{([a-zA-Z0-9_]+)\}/g, function (match, p) {
        return params[p] !== undefined ? params[p] : match;
      });
    }
    return val;
  }

  function applyTranslations() {
    if (typeof document === 'undefined') return;

    var i18nElements = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < i18nElements.length; i++) {
      var el = i18nElements[i];
      var key = el.getAttribute('data-i18n');
      var translated = t(key);
      if (translated && translated !== key) {
        if (translated.indexOf('<') !== -1 && translated.indexOf('>') !== -1) {
          el.innerHTML = translated;
        } else {
          el.textContent = translated;
        }
      }
    }

    var placeholderElements = document.querySelectorAll('[data-i18n-placeholder]');
    for (var p = 0; p < placeholderElements.length; p++) {
      var pel = placeholderElements[p];
      var pkey = pel.getAttribute('data-i18n-placeholder');
      pel.setAttribute('placeholder', t(pkey));
    }

    var titleElements = document.querySelectorAll('[data-i18n-title]');
    for (var ti = 0; ti < titleElements.length; ti++) {
      var tel = titleElements[ti];
      tel.setAttribute('title', t(tel.getAttribute('data-i18n-title')));
    }

    var ariaElements = document.querySelectorAll('[data-i18n-aria-label]');
    for (var a = 0; a < ariaElements.length; a++) {
      var ael = ariaElements[a];
      ael.setAttribute('aria-label', t(ael.getAttribute('data-i18n-aria-label')));
    }
  }

  function setLanguage(lang) {
    if (!lang || SUPPORTED_LANGS.indexOf(lang) === -1) {
      lang = DEFAULT_LANG;
    }
    currentLanguage = lang;
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem(STORAGE_KEY, lang);
      }
    } catch (e) {}

    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.lang = lang;
    }

    var selects = typeof document !== 'undefined' ? document.querySelectorAll('#globalLangSelect, .global-lang-select') : [];
    for (var s = 0; s < selects.length; s++) {
      selects[s].value = lang;
    }

    applyTranslations();

    if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
      window.dispatchEvent(
        new CustomEvent('sahay:languageChanged', {
          detail: {
            language: lang,
            voiceLocale: getVoiceLocale(lang),
          },
        })
      );
    }
  }

  function init() {
    var stored = DEFAULT_LANG;
    try {
      if (typeof localStorage !== 'undefined') {
        stored = localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
      }
    } catch (e) {}
    if (SUPPORTED_LANGS.indexOf(stored) === -1) {
      stored = DEFAULT_LANG;
    }

    setLanguage(stored);

    if (typeof document !== 'undefined') {
      document.addEventListener('change', function (e) {
        if (e.target && (e.target.id === 'globalLangSelect' || (e.target.classList && e.target.classList.contains('global-lang-select')))) {
          setLanguage(e.target.value);
        }
      });
    }
  }

  if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', init);
    } else {
      init();
    }
  }

  return {
    init: init,
    t: t,
    getLanguage: getLanguage,
    setLanguage: setLanguage,
    getVoiceLocale: getVoiceLocale,
    applyTranslations: applyTranslations,
    LOCALES: LOCALES,
  };
